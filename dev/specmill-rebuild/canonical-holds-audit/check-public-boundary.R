# Source-only evidence exemptions must not weaken built-artifact checks.
source('dev/check_public_api.R')
root <- tempfile('boundary-source-')
dir.create(file.path(root,'R'),recursive=TRUE)
dir.create(file.path(root,'dev'))
dir.create(file.path(root,'.planning'))
stopifnot(system2('git',c('init','--quiet',shQuote(root)))==0L)
writeLines('url <- "https://hcd.rtpnc.epa.gov/api"',file.path(root,'R/public.R'))
staging <- paste0('https://cim.', 'sciencedataexperts.com/api')
writeLines(staging,file.path(root,'dev/evidence.txt'))
writeLines(staging,file.path(root,'.planning/evidence.md'))
stopifnot(system2('git',c('-C',shQuote(root),'add','.'))==0L)
error <- tryCatch(check_public_api(root),error=identity)
stopifnot(inherits(error,'error')) # A rendered-site Git checkout is still public.
writeLines(c('Package: ComptoxR','Version: 3.0.0'),file.path(root,'DESCRIPTION'))
stopifnot(system2('git',c('-C',shQuote(root),'add','DESCRIPTION'))==0L)
stopifnot(isTRUE(check_public_api(root)))
writeLines(staging,file.path(root,'R/public.R'))
error <- tryCatch(check_public_api(root),error=identity)
stopifnot(inherits(error,'error'),grepl('Non-production address found:',conditionMessage(error),fixed=TRUE))
writeLines('url <- "https://hcd.rtpnc.epa.gov/api"',file.path(root,'R/public.R'))
unlink(file.path(root,'.git'),recursive=TRUE)
error <- tryCatch(check_public_api(root),error=identity)
stopifnot(inherits(error,'error'),grepl('Non-production address found:',conditionMessage(error),fixed=TRUE))
unlink(root,recursive=TRUE)
cat('Source evidence allowed; runtime and built-artifact non-production URLs still rejected PASS\n')

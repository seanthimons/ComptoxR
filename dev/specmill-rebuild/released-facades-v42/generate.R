source('dev/specmill-rebuild/released-facades-v42/setup.R')
work <- tempfile('released-facades-'); dir.create(work)
for (path in c('R', 'schema', 'man', 'data', 'inst', 'tests', 'dev/specmill-rebuild/released-facades-v42')) {
  dir.create(dirname(file.path(work, path)), recursive = TRUE, showWarnings = FALSE)
  stopifnot(file.copy(path, dirname(file.path(work, path)), recursive = TRUE))
}
file.copy(c('DESCRIPTION', 'NAMESPACE', 'air.toml'), work)
config <- file.path(folder, 'config.yml')
mappings <- lapply(yaml::read_yaml(config)$services, yaml::read_yaml)
outputs <- unique(unlist(lapply(mappings, function(mapping) vapply(mapping$operations, `[[`, '', 'file'))))
unlink(file.path(work, outputs))
unlink(file.path(work, 'man', paste0(unlist(lapply(mappings, function(mapping) vapply(mapping$operations, `[[`, '', 'name'))), '.Rd')))
args <- list(root = work, config = config, callbacks = callbacks, artifacts = c('wrappers', 'documentation'), validation = TRUE)
args$adopt <- list(NAMESPACE = specmill:::output_hash(file.path(work, 'NAMESPACE')))
plan <- do.call(specmill::generate_client, c(args, list(mode = 'apply')))
print(plan)
stopifnot(!length(plan$diagnostics), !length(plan$mapping_diagnostics), !length(plan$retained_diagnostics), !length(plan$drift))
args$adopt <- list()
args$artifacts <- 'wrappers'
fresh <- do.call(specmill::generate_client, c(args, list(mode = 'check')))
print(fresh)
stopifnot(!length(fresh$diagnostics), !length(fresh$mapping_diagnostics), !length(fresh$retained_diagnostics), !length(fresh$drift),
  all(vapply(fresh$files, function(file) identical(file$action, 'unchanged'), FALSE)))
manifest <- jsonlite::read_json(file.path(work, '.specmill/manifest.json'))
stopifnot(all(vapply(names(manifest$files), function(path)
  identical(specmill:::output_hash(file.path(work, path)), manifest$files[[path]]$hash), FALSE)))
file.copy(file.path(work, 'NAMESPACE'), file.path(folder, 'isolated-NAMESPACE.txt'), overwrite = TRUE)
saveRDS(list(generation = plan, freshness = fresh, ownership = manifest, metadata = metadata), file.path(folder, 'generation.rds'))
for (path in outputs) stopifnot(file.copy(file.path(work, path), path, overwrite = TRUE))
for (path in names(manifest$files)[startsWith(names(manifest$files), 'man/')])
  stopifnot(file.copy(file.path(work, path), path, overwrite = TRUE))
unlink(work, recursive = TRUE)

base <- '/home/sxthi/.cache/comptoxr-specmill-finish/release50-verification/pubchem-candidate'
loadNamespace('specmill',lib.loc='/home/sxthi/.cache/comptoxr-specmill-finish/release50-verification/library')
cb <- new.env(parent=baseenv());sys.source('dev/specmill_callbacks.R',cb);sys.source(file.path(base,'callbacks.R'),cb)
stage <- file.path(base,'project')
files <- file.path(stage,'R',paste0(c('pubchem_search','pubchem_properties','pubchem_synonyms'),'.R'))
hash <- function(path) digest::digest(file=path,algo='sha256')
before <- setNames(vapply(files,hash,''),basename(files))
args <- list(root=stage,config='specmill.yml',callbacks=cb,validation=TRUE,artifacts=c('wrappers','documentation'))
a <- do.call(specmill::generate_client,c(args,list(mode='apply')))
f <- do.call(specmill::generate_client,c(args,list(mode='check')))
after <- setNames(vapply(files,hash,''),basename(files))
stopifnot(!length(f$diagnostics),!length(f$mapping_diagnostics),!length(f$drift),!length(f$retained_diagnostics),all(vapply(f$files,function(x) x$action %in% c('unchanged','retained'),TRUE)))
m <- jsonlite::read_json(file.path(stage,'.specmill/manifest.json'))
for(p in names(m$files)) stopifnot(identical(digest::digest(paste(readLines(file.path(stage,p),warn=FALSE),collapse='\n'),algo='sha256',serialize=FALSE),m$files[[p]]$hash))
jsonlite::write_json(list(all_owner_hashes_match=TRUE,owners=length(m$files),public_wrapper_hashes=as.list(after),repeated_portable_callbacks_public_bytes_identical=identical(before,after),fresh=TRUE),file.path(base,'portable-verification.json'),auto_unbox=TRUE,pretty=TRUE)
saveRDS(list(apply=a,fresh=f),file.path(base,'portable-generation.rds'))
cat('Portable callback module generation/check PASS, all ownership hashes verified.\n')
